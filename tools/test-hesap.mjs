// Hesaplama aracının hesap modelini sınar: npm run test:hesap
// Beklenen değerler örnek girdilerle elle hesaplanmıştır.
import { readFileSync } from 'node:fs';
import vm from 'node:vm';
const ctx = { window: {} }; ctx.globalThis = ctx;
vm.runInNewContext(readFileSync(new URL('../assets/hesap.js', import.meta.url), 'utf8'), ctx);
const { defaults, compute } = ctx.window.EmekHesapModel;
let fail = 0;
const near = (name, got, want, tol = 0.01) => { const ok = Math.abs(got - want) <= tol; if (!ok) fail++; console.log(ok ? '  tamam' : '  HATA ', name, ok ? '' : `beklenen ${want}, bulunan ${got}`); };
const yes = (name, cond) => { if (!cond) fail++; console.log(cond ? '  tamam' : '  HATA ', name); };

const d = defaults(), r = compute(d);
console.log('Örnek değerler');
yes('günlük ücretler 720 / 960 / 1440', d.machines.map(m => m.dayRate).join() === '720,960,1440');
yes('yıllık sigorta 1050 / 2100 / 3600', d.machines.map(m => m.insYear).join() === '1050,2100,3600');
near('tezgâh sayısı', r.N, 8);
near('tezgâh başına ayda dolu gün', r.busy, 16.9);
near('aylık ciro', r.gross, 16.9 * (3 * 720 + 3 * 960 + 2 * 1440));
near('ortalama platform payı', r.fee, 0.155, 1e-9);
near('platform payı (şirket kârı)', r.pf, 133848 * 0.155);
near('operatör sayısı', r.people.operators, 8);
near('vardiya başına operatör', r.people.opPerShift, 4);
near('planlamacı sayısı', r.people.planners, 1);
near('operatör gideri', r.cost.operators, 8 * 60 * 26);
near('planlamacı gideri', r.cost.planners, 1 * 90 * 26);
near('diğer ekip gideri', r.cost.others, (115 + 70) * 26);
near('elektrik', r.cost.elec, 8 * 16.9 * 24);
near('takım ve sarf', r.cost.tool, 8 * 16.9 * 48);
near('bakım', r.cost.maint, 1665000 * 0.03 / 12);
near('sigorta', r.cost.ins, (3 * 1050 + 3 * 2100 + 2 * 3600) / 12);
near('toplam işletme gideri', r.cost.total, 42014.4);
near('yatırımcılara kalan', r.investorNet, 133848 - 20746.44 - 42014.4);
near('yatırımcı neti, tezgâh başına aylık', r.investorOne, 71087.16 / 8);
near('yatırımcı neti, tezgâh başına günlük', r.day.investorOne, 71087.16 / 8 / 26);
near('şirketin günlük kârı', r.day.profit, 20746.44 / 26);
near('ekibin günlük maliyeti', r.day.staff, 755);
near('başabaş doluluk', r.breakEven, 32280 / (26 * 7920 * 0.845 - 8 * 26 * 72), 1e-6);
near('tesis kurulumu', r.facility, 135000);
near('tesis kurulumunun geri dönüşü (ay)', r.facilityPaybackMonths, 135000 / 20746.44, 1e-6);
near('tezgâh yatırımı', r.machinesInvest, 3 * 109500 + 3 * 216500 + 2 * 369500);
const t4 = r.types[1];
near('4 eksen aylık işletme gideri', t4.opCost, 26730 / 8 + 16.9 * 72 + 210000 * 0.03 / 12 + 2100 / 12);
near('4 eksen dolu günde yatırımcıya', t4.netDay, 960 - 960 * 0.155 - 5258.05 / 16.9);
near('4 eksen aylık net', t4.net, 16224 - 2514.72 - 5258.05);
near('4 eksen geri dönüş (yıl)', t4.paybackYears, 216500 / (8451.23 * 12), 1e-4);

console.log('Tutarlılık');
near('ciro = yatırımcılara + işletme giderleri + platform payı', r.investorNet + r.cost.total + r.pf, r.gross);
near('tezgâh netlerinin toplamı = yatırımcılara kalan', r.types.reduce((a, t) => a + t.net * t.count, 0), r.investorNet);
near('başabaş dolulukta yatırımcı neti sıfır', compute({ ...d, util: r.breakEven * 100 }).investorNet, 0, 0.5);
near('günlük = aylık ÷ çalışma günü', r.day.gross * 26, r.gross);
yes('doluluk artınca yatırımcı neti artar', compute({ ...d, util: 80 }).investorNet > r.investorNet);
yes('vardiya artınca operatör artar', compute({ ...d, shifts: 3 }).people.operators === 12);
yes('sigorta artınca yatırımcı neti düşer', compute({ ...d, machines: d.machines.map(m => ({ ...m, insYear: m.insYear * 2 })) }).investorNet < r.investorNet);
yes('slot aşımı bildirilir', compute({ ...d, slots: 6 }).free === -2);

console.log('Sınır durumlar');
const z = compute({ ...d, machines: [] });
yes('tezgâh yokken sayı hatası yok', [z.gross, z.profit, z.investorOne, z.investorYearly, z.day.investorOne].every(Number.isFinite) && z.costBusyDay === null && z.breakEven === Infinity);
const u0 = compute({ ...d, util: 0 });
yes('doluluk sıfırken ciro sıfır, dolu gün maliyeti boş', u0.gross === 0 && u0.costBusyDay === null && u0.types[0].netDay === null && u0.types[0].paybackYears === Infinity);
const g0 = compute({ ...d, days: 0 });
yes('çalışma günü sıfırken günlük tutarlar sıfır', g0.day.gross === 0 && g0.day.profit === 0 && Number.isFinite(g0.investorOne));
yes('boş ve hatalı girişler sıfır sayılır', Math.abs(compute({ ...d, rent: '', elecDay: 'abc', toolDay: -5 }).cost.total - (42014.4 - 5000 - 3244.8 - 6489.6)) < 0.01);
yes('operatör oranı sıfırsa operatör yok', compute({ ...d, perOperator: 0 }).people.operators === 0);
yes('zarar eden tezgâhın geri dönüşü yok', compute({ ...d, util: 5 }).types[0].paybackYears === Infinity);
console.log(fail ? `\n${fail} sınama başarısız` : '\nTüm sınamalar geçti');
process.exit(fail ? 1 : 0);
